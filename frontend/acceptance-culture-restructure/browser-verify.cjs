// 实际 8002 页面与 Edge Chromium；无模型响应、地图或故事资料替身。
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/Rocket/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const output = __dirname;
const evidence = {url:'http://localhost:8002', viewport:{width:1920,height:1080}, browser:'Edge Chromium headless', fixture:false, checks:[], consoleErrors:[], pageErrors:[]};
(async () => {
  const browser = await chromium.launch({channel:'msedge',headless:true});
  const page = await browser.newPage({viewport:evidence.viewport});
  page.on('pageerror', error => evidence.pageErrors.push(error.message));
  page.on('console', message => {if(message.type()==='error')evidence.consoleErrors.push(message.text());});
  const check = (name, data={}) => evidence.checks.push({name,pass:true,...data});
  const screenshot = async name => { await page.evaluate(async()=>{await Promise.all(document.getAnimations().filter(x=>x.effect?.getTiming().iterations!==Infinity).map(x=>x.finished.catch(()=>{})));}); return page.screenshot({path:path.join(output,name+'.png')}); };
  const dimensions = async name => {
    const value = await page.evaluate(() => ({viewport:innerWidth,document:document.documentElement.scrollWidth,panels:[...document.querySelectorAll('[data-view-panel]:not([hidden])')].map(x=>({id:x.id,width:x.clientWidth,scrollWidth:x.scrollWidth}))}));
    assert.ok(value.document<=1920, name+' document overflow');
    value.panels.forEach(x=>assert.ok(x.scrollWidth<=x.width+1,name+' panel overflow: '+x.id));
    check(name+' width',value);
  };
  try {
    await page.goto(evidence.url);
    await page.waitForLoadState('networkidle');
    assert.equal(await page.locator('.content-switch button').count(),5);
    assert.equal(await page.locator('.chenshou-portrait:visible').count(),1);
    assert.equal(await page.locator('#story-cards .story-card').count(),5);
    assert.equal(await page.locator('#story-preview-map').count(),1);
    const entryBounds = await page.locator('.culture-entry').evaluateAll(xs=>xs.map(x=>{const r=x.getBoundingClientRect();return {x:r.x,y:r.y,right:r.right,bottom:r.bottom};}));
    assert.ok(entryBounds[0].right<entryBounds[1].x);
    assert.ok(entryBounds.every(x=>x.bottom<1080));
    check('hero and two entrances are visible on first screen',{entryBounds});
    await dimensions('initial');await screenshot('culture-initial');
    await page.mouse.move(950,300);await page.mouse.wheel(0,150);
    await page.waitForFunction(()=>document.querySelector('#welcome-view').scrollTop>0);
    const freeScroll=await page.locator('#welcome-view').evaluate(x=>({top:x.scrollTop,max:x.scrollHeight-x.clientHeight}));
    assert.ok(freeScroll.top>0&&freeScroll.top<freeScroll.max,'wheel can stop between top and bottom');
    check('vertical wheel has continuous intermediate positions',freeScroll);
    await screenshot('culture-scroll-midpoint');
    await page.locator('#welcome-view').evaluate(x=>x.scrollTop=0);
    const rail=page.locator('#story-cards');
    assert.ok(await rail.evaluate(x=>x.scrollWidth>x.clientWidth));
    await page.locator('#story-scroll-next').click();
    await page.waitForFunction(()=>document.querySelector('#story-cards').scrollLeft>0);
    check('five themes scroll horizontally');
    await page.locator('#story-cards [data-story-id="shudao-xunzong"] .story-card').click();
    assert.equal(await page.locator('#welcome-view').isVisible(),true);
    assert.equal(await page.locator('#preview-chapters li').count(),3);
    assert.equal(await page.locator('#preview-story-open').innerText(),'进入故事地图');
    assert.equal(await page.locator('#story-cards [aria-pressed="true"]').count(),1);
    await dimensions('selected');await screenshot('culture-selected');
    check('selecting a story updates chapters and shared map without navigating');
    await page.locator('#preview-detail-open').click();
    await page.waitForFunction(()=>document.querySelector('#story-detail-map #story-preview-map'));
    const columns=await page.locator('.story-detail-layout').evaluate(x=>getComputedStyle(x).gridTemplateColumns);
    assert.equal(await page.locator('#story-detail-sidebar .story-chapter-axis > li').count(),3);
    assert.equal(await page.locator('#story-preview-map').count(),1);
    await dimensions('detail');await screenshot('story-detail');
    check('story detail has chapter sidebar and reading with same SVG',{columns});
    await page.locator('#story-view [data-content-view="welcome"]').click();
    await page.waitForFunction(()=>document.querySelector('#culture-map-home #story-preview-map'));
    await page.locator('#preview-story-open').click();
    await page.waitForSelector('#map-view.story-mode');
    assert.equal(await page.locator('#map-view').getAttribute('data-story-id'),'shudao-xunzong');
    await dimensions('story map');await screenshot('story-map');
    check('chaptered story enters original story map');
    await page.locator('.content-switch [data-content-view="welcome"]').click();
    await page.locator('#preview-clear').click();
    assert.equal(await page.locator('#preview-story-open').innerText(),'打开四川地图');
    await page.locator('#preview-story-open').click();
    assert.equal(await page.locator('#map-view').evaluate(x=>x.classList.contains('story-mode')),false);
    await dimensions('ordinary map');check('cleared selection opens ordinary map');
    await page.locator('.content-switch [data-content-view="welcome"]').click();
    await page.locator('#story-cards [data-story-id="chenshou"] .story-card').click();
    await page.locator('#preview-story-open').click();
    assert.equal(await page.locator('#map-view').evaluate(x=>x.classList.contains('story-mode')),false);
    assert.match(await page.locator('#map-route-status').innerText(),/章节与地点待补充/);
    check('pending theme opens ordinary map with explicit boundary');
    await page.locator('.content-switch [data-content-view="welcome"]').click();
    await page.locator('#preview-clear').click();
    await page.locator('#culture-places').evaluate(x=>x.scrollIntoView());
    assert.equal(await page.locator('#story-buildings .building-card').count(),5);
    assert.equal(await page.locator('.culture-grid .culture-card').count(),3);
    await dimensions('places');await screenshot('culture-places');
    assert.equal(await page.locator('#culture-places').evaluate(x=>x.tagName),'SECTION');
    assert.equal(await page.locator('#welcome-view').evaluate(x=>getComputedStyle(x).overflowY),'auto');
    assert.equal(await page.locator('#culture-page-track').count(),0);
    check('continuous scrolling reaches five building nodes and three unfolded culture cards');
    await page.locator('#story-buildings .building-card button').first().click();
    assert.equal(await page.locator('#node-view').isVisible(),true);
    await dimensions('place detail beside culture exploration');
    await page.locator('#node-back').click();
    assert.equal(await page.locator('#welcome-view').isVisible(),true);
    check('place detail returns to culture exploration');
    await page.locator('#journey-desk').evaluate(x=>x.scrollIntoView());
    await page.evaluate(async()=>{await Promise.all(document.getAnimations().filter(x=>x.effect?.getTiming().iterations!==Infinity).map(x=>x.finished.catch(()=>{})));});
    await page.locator('#journey-days').selectOption('2');
    await page.locator('#journey-origin').fill('南充');
    await page.locator('#journey-interest').selectOption('史书与遗迹');
    await page.locator('#journey-person').selectOption('诸葛亮');
    assert.equal(await page.locator('#hero-send').isEnabled(),true);
    await screenshot('recommendation-conditions');
    const requestPromise = page.waitForRequest(request=>request.method()==='POST'&&['/chat','/chat/stream'].includes(new URL(request.url()).pathname));
    await page.locator('#hero-send').click();
    const request=await requestPromise;
    evidence.recommendationRequest=request.postDataJSON();
    for(const condition of ['2 天','南充','史书与遗迹','诸葛亮'])assert.ok(request.postData().includes(condition));
    check('structured recommendation uses real chat request');
    await dimensions('recommendation with chat open');
    const clipped = await page.locator('.culture-entry').evaluateAll(xs=>xs.map(x=>{const r=x.getBoundingClientRect();const viewport=document.querySelector('#welcome-view').getBoundingClientRect();return {bottom:r.bottom,viewportBottom:viewport.bottom};}));
    assert.ok(clipped.every(x=>x.bottom<=x.viewportBottom),'both entrances fit with chat open');
    // 实际请求可能持续生成，记录实测范围，不声称核验模型回复。
    await screenshot('recommendation-chat');
    await page.locator('#culture-places').evaluate(x=>x.scrollIntoView());
    await page.evaluate(async()=>{await Promise.all(document.getAnimations().filter(x=>x.effect?.getTiming().iterations!==Infinity).map(x=>x.finished.catch(()=>{})));});
    await dimensions('places with chat open');await screenshot('culture-places-chat');
    check('unfolded places remain reachable with chat open');
    evidence.modelReplyVerified=false;
    assert.deepEqual(evidence.pageErrors,[]);assert.deepEqual(evidence.consoleErrors,[]);
    check('zero observed console and page errors');
    evidence.pass=true;
  } catch(error) {
    evidence.pass=false;evidence.failure=error.stack;
    await screenshot('failure');throw error;
  } finally {
    evidence.observedAt=new Date().toISOString();
    fs.writeFileSync(path.join(output,'browser-green.json'),JSON.stringify(evidence,null,2));
    await browser.close();
  }
})().catch(error=>{console.error(error);process.exitCode=1;});
